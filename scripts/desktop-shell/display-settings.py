#!/usr/bin/env python3
"""Preview and confirm edits to the existing nwg-displays monitor rules."""

import contextlib
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))) / "hypr/monitors.lua"
RUNTIME = Path(os.environ["XDG_RUNTIME_DIR"])
PENDING = RUNTIME / "desktop-shell-display-preview.json"
TIMER = "desktop-shell-display-preview.timer"
RULE = re.compile(r"hl\.monitor\s*\(\s*\{[^{}]*\}\s*\)")
NAME = re.compile(r'\boutput\s*=\s*"([A-Za-z0-9_.-]+)"')
MODE = re.compile(r"^[0-9]+x[0-9]+@[0-9]+(?:\.[0-9]+)?(?:Hz)?$")


def command(*args):
    """Run a compositor or user service command with a bounded timeout."""
    result = subprocess.run(args, check=True, capture_output=True, text=True, timeout=8)
    return result.stdout.strip()


def read_monitors():
    """Return compositor-authoritative display state."""
    return json.loads(command("hyprctl", "-j", "monitors", "all"))


def generated_rules(text):
    """Accept only the existing generated monitor file, not arbitrary Lua."""
    if not text.lstrip().startswith("-- Generated by nwg-displays"):
        return {}
    rules = {}
    for match in RULE.finditer(text):
        fields = match.group().split("{", 1)[1].rsplit("}", 1)[0]
        literal = r'[A-Za-z_][A-Za-z0-9_]*\s*=\s*(?:"[^"\\\n]*"|-?\d+(?:\.\d+)?|true|false)'
        if not re.fullmatch(r"\s*" + literal + r"(?:\s*,\s*" + literal + r")*\s*,?\s*", fields):
            return {}
        name = NAME.search(match.group())
        if not name or name.group(1) in rules:
            return {}
        rules[name.group(1)] = match.group()
    remainder = RULE.sub("", text)
    if any(line.strip() and not line.lstrip().startswith("--") for line in remainder.splitlines()):
        return {}
    return rules


def rule_field(rule, name, value):
    """Replace one known literal field while retaining other native options."""
    value = json.dumps(value, ensure_ascii=True)
    expression = re.compile(r"(\b" + re.escape(name) + r"\s*=\s*)(?:\"[^\"]*\"|-?\d+(?:\.\d+)?)")
    matches = list(expression.finditer(rule))
    if len(matches) == 1:
        return expression.sub(lambda match: match.group(1) + value, rule, count=1)
    if matches or re.search(r"\b" + re.escape(name) + r"\s*=", rule):
        raise ValueError("Unrecognized monitor rule field")
    end = rule.rindex("}")
    body = rule[:end].rstrip()
    return body + ("" if body.endswith(",") else ",") + "\n    " + name + " = " + value + "\n" + rule[end:]


def mode_value(monitor):
    """Normalize the live mode to the same representation as advertised modes."""
    return f"{monitor['width']}x{monitor['height']}@{monitor['refreshRate']:.3f}"


def mode_parts(mode):
    """Parse an advertised mode string, with an optional Hz suffix."""
    if not MODE.fullmatch(mode):
        raise ValueError("Invalid monitor mode")
    size, rate = mode.removesuffix("Hz").split("@")
    width, height = map(int, size.split("x"))
    return width, height, float(rate)


def same_mode(left, right):
    """Compare refresh rates with the precision used by compositor readback."""
    a, b = mode_parts(left), mode_parts(right)
    return a[:2] == b[:2] and abs(a[2] - b[2]) < 0.08


def build_rule(rule, mode, scale, transform, x, y):
    """Edit only the mode, scale, orientation and position fields."""
    for key, value in (("mode", mode.removesuffix("Hz")), ("scale", scale),
                       ("transform", transform), ("position", f"{x}x{y}")):
        rule = rule_field(rule, key, value)
    return rule


def matches(monitor, target):
    """Check the actual applied monitor dimensions, scale and placement."""
    return (
        not monitor.get("disabled", False)
        and same_mode(mode_value(monitor), target["mode"])
        and abs(monitor["scale"] - target["scale"]) < 0.01
        and monitor["transform"] == target["transform"]
        and monitor["x"] == target["x"] and monitor["y"] == target["y"]
    )


def atomic_write(path, data, mode=0o600):
    """Replace a state or configuration file without partially writing it."""
    fd, temporary = tempfile.mkstemp(prefix=path.name + "-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), mode)
        os.replace(temporary, path)
    finally:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(temporary)


def config_text():
    """Read the current native layout without creating a competing file."""
    return CONFIG.read_text() if CONFIG.is_file() and not CONFIG.is_symlink() else ""


def digest(text):
    """Identify the exact native configuration used to begin the preview."""
    return hashlib.sha256(text.encode()).hexdigest()


def pending():
    """Return the single display transaction, if present."""
    if not PENDING.exists():
        return None
    return json.loads(PENDING.read_text())


def apply_rule(rule):
    """Use the supported Hyprland Lua monitor interface."""
    reply = command("hyprctl", "eval", rule)
    if "error" in reply.lower() or "failed" in reply.lower():
        raise ValueError(reply)


def stop_timer():
    """Disarm the independent rollback timer."""
    with contextlib.suppress(subprocess.SubprocessError):
        command("systemctl", "--user", "stop", TIMER)


def rollback(transaction):
    """Restore live values without modifying the saved layout."""
    if digest(config_text()) == transaction["digest"]:
        apply_rule(transaction["original"])
    else:
        # An external editor changed the authoritative file; reload that file
        # rather than writing the older snapshot over its changes.
        command("hyprctl", "reload")
    PENDING.unlink(missing_ok=True)
    stop_timer()


def status():
    """Return real monitor values and available choices, not requested values."""
    rules = generated_rules(config_text())
    monitors = read_monitors()
    for monitor in monitors:
        monitor["editable"] = (
            monitor["name"] in rules and not monitor.get("disabled", False)
            and monitor.get("mirrorOf", "none") == "none" and monitor.get("transform", 0) <= 3
        )
        if monitor["editable"]:
            monitor["currentMode"] = mode_value(monitor)
        else:
            monitor["currentMode"] = ""
    transaction = pending()
    return {"monitors": monitors, "deadline": transaction["deadline"] if transaction else 0}


def verify_target(name, target):
    """Wait briefly for actual compositor readback after applying a rule."""
    for _ in range(8):
        monitor = next((entry for entry in read_monitors() if entry["name"] == name), None)
        if monitor and matches(monitor, target):
            return
        time.sleep(0.2)
    raise ValueError("Display did not confirm the requested configuration")


def preview(args):
    """Validate a staged rule and arm rollback before touching the compositor."""
    if pending():
        raise ValueError("Keep or revert the existing preview first")
    name, mode, raw_scale, raw_transform, raw_x, raw_y = args
    text = config_text()
    rule = generated_rules(text).get(name)
    current = next((entry for entry in read_monitors() if entry["name"] == name), None)
    if not rule or not current or current.get("disabled") or current.get("mirrorOf", "none") != "none" or current.get("transform", 0) > 3:
        raise ValueError("Use the native display editor for this layout")
    scale, transform, x, y = float(raw_scale), int(raw_transform), int(raw_x), int(raw_y)
    if not 0.75 <= scale <= 3 or not 0 <= transform <= 3 or abs(x) > 32768 or abs(y) > 32768:
        raise ValueError("Invalid display geometry")
    if not any(same_mode(mode, candidate) for candidate in [mode_value(current), *current.get("availableModes", [])] if MODE.fullmatch(candidate)):
        raise ValueError("Mode is not advertised by this output")
    original = build_rule(rule, mode_value(current), current["scale"], current["transform"], current["x"], current["y"])
    replacement = build_rule(rule, mode, scale, transform, x, y)
    target = {"mode": mode, "scale": scale, "transform": transform, "x": x, "y": y}
    transaction = {"name": name, "digest": digest(text), "original": original,
                   "replacement": replacement, "target": target, "deadline": time.time() + 20}
    atomic_write(PENDING, json.dumps(transaction))
    try:
        command("systemctl", "--user", "restart", TIMER)
    except subprocess.SubprocessError:
        PENDING.unlink(missing_ok=True)
        raise
    try:
        apply_rule(replacement)
        verify_target(name, target)
    except (ValueError, subprocess.SubprocessError):
        rollback(transaction)
        raise


def confirm(transaction):
    """Persist the verified preview to the existing native monitor file."""
    text = config_text()
    if time.time() >= transaction["deadline"] or digest(text) != transaction["digest"]:
        rollback(transaction)
        raise ValueError("Preview expired or the native layout changed")
    verify_target(transaction["name"], transaction["target"])
    previous = generated_rules(text).get(transaction["name"])
    if not previous or text.count(previous) != 1:
        rollback(transaction)
        raise ValueError("Native layout changed")
    atomic_write(CONFIG, text.replace(previous, transaction["replacement"], 1), CONFIG.stat().st_mode & 0o777)
    PENDING.unlink(missing_ok=True)
    stop_timer()


def main(args):
    """Serialize preview, rollback and confirmation, including timer callbacks."""
    with (RUNTIME / "desktop-shell-display-preview.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        action = args[0] if args else "status"
        transaction = pending()
        if transaction and (action == "rollback" or time.time() >= transaction["deadline"]):
            rollback(transaction)
            transaction = None
        if action == "preview":
            preview(args[1:])
        elif action == "keep":
            if not transaction:
                raise ValueError("No active preview")
            confirm(transaction)
        elif action not in ("status", "rollback"):
            raise ValueError("Unknown display action")
        print(json.dumps(status()))


if __name__ == "__main__":
    try:
        main(sys.argv[1:])
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
