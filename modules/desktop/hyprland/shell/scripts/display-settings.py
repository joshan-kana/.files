#!/usr/bin/env python3
"""Preview and confirm edits to the existing nwg-displays monitor rules."""

import contextlib
import fcntl
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time
from pathlib import Path

CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))) / "hypr/monitors.lua"
PROFILES = CONFIG.parent.parent / "desktop-shell/display-profiles.json"
RUNTIME = Path(os.environ["XDG_RUNTIME_DIR"])
PENDING = RUNTIME / "desktop-shell-display-preview.json"
TIMER = "desktop-shell-display-preview.timer"
RULE = re.compile(r"hl\.monitor\s*\(\s*\{[^{}]*\}\s*\)")
NAME = re.compile(r'\boutput\s*=\s*"([A-Za-z0-9_.-]+)"')
MODE = re.compile(r"^[0-9]+x[0-9]+@[0-9]+(?:\.[0-9]+)?(?:Hz)?$")


def command(*args):
    """Run a compositor or user service command with a bounded timeout."""
    result = subprocess.run(args, check=True, capture_output=True, text=True, timeout=8)
    return result.stdout.strip()


def read_monitors():
    """Return compositor-authoritative display state."""
    return json.loads(command("hyprctl", "-j", "monitors", "all"))


def generated_rules(text):
    """Accept only the existing generated monitor file, not arbitrary Lua."""
    if not text.lstrip().startswith("-- Generated by nwg-displays"):
        return {}
    rules = {}
    for match in RULE.finditer(text):
        fields = match.group().split("{", 1)[1].rsplit("}", 1)[0]
        literal = r'[A-Za-z_][A-Za-z0-9_]*\s*=\s*(?:"[^"\\\n]*"|-?\d+(?:\.\d+)?|true|false)'
        if not re.fullmatch(r"\s*" + literal + r"(?:\s*,\s*" + literal + r")*\s*,?\s*", fields):
            return {}
        name = NAME.search(match.group())
        if not name or name.group(1) in rules:
            return {}
        rules[name.group(1)] = match.group()
    remainder = RULE.sub("", text)
    if any(line.strip() and not line.lstrip().startswith("--") for line in remainder.splitlines()):
        return {}
    return rules


def rule_field(rule, name, value):
    """Replace one known literal field while retaining other native options."""
    value = json.dumps(value, ensure_ascii=True)
    expression = re.compile(r"(\b" + re.escape(name) + r"\s*=\s*)(?:\"[^\"]*\"|-?\d+(?:\.\d+)?)")
    matches = list(expression.finditer(rule))
    if len(matches) == 1:
        return expression.sub(lambda match: match.group(1) + value, rule, count=1)
    if matches or re.search(r"\b" + re.escape(name) + r"\s*=", rule):
        raise ValueError("Unrecognized monitor rule field")
    end = rule.rindex("}")
    body = rule[:end].rstrip()
    return body + ("" if body.endswith(",") else ",") + "\n    " + name + " = " + value + "\n" + rule[end:]


def mode_value(monitor):
    """Normalize the live mode to the same representation as advertised modes."""
    return f"{monitor['width']}x{monitor['height']}@{monitor['refreshRate']:.3f}"


def mode_parts(mode):
    """Parse an advertised mode string, with an optional Hz suffix."""
    if not MODE.fullmatch(mode):
        raise ValueError("Invalid monitor mode")
    size, rate = mode.removesuffix("Hz").split("@")
    width, height = map(int, size.split("x"))
    return width, height, float(rate)


def same_mode(left, right):
    """Compare refresh rates with the precision used by compositor readback."""
    a, b = mode_parts(left), mode_parts(right)
    return a[:2] == b[:2] and abs(a[2] - b[2]) < 0.08


def build_rule(rule, mode, scale, transform, x, y):
    """Edit only the mode, scale, orientation and position fields."""
    for key, value in (("mode", mode.removesuffix("Hz")), ("scale", scale), ("transform", transform), ("position", f"{x}x{y}")):
        rule = rule_field(rule, key, value)
    return rule


def matches(monitor, target):
    """Check the actual applied monitor dimensions, scale and placement."""
    return (
        not monitor.get("disabled", False)
        and same_mode(mode_value(monitor), target["mode"])
        and abs(monitor["scale"] - target["scale"]) < 0.01
        and monitor["transform"] == target["transform"]
        and monitor["x"] == target["x"]
        and monitor["y"] == target["y"]
    )


def atomic_write(path, data, mode=0o600):
    """Replace a state or configuration file without partially writing it."""
    fd, temporary = tempfile.mkstemp(prefix=path.name + "-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), mode)
        os.replace(temporary, path)
    finally:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(temporary)


def config_text():
    """Read the current native layout without creating a competing file."""
    return CONFIG.read_text() if CONFIG.is_file() and not CONFIG.is_symlink() else ""


def digest(text):
    """Identify the exact native configuration used to begin the preview."""
    return hashlib.sha256(text.encode()).hexdigest()


def pending():
    """Return the single display transaction, if present."""
    if not PENDING.exists():
        return None
    return json.loads(PENDING.read_text())


def apply_rule(rule):
    """Use the supported Hyprland Lua monitor interface."""
    reply = command("hyprctl", "eval", rule)
    if "error" in reply.lower() or "failed" in reply.lower():
        raise ValueError(reply)


def stop_timer():
    """Disarm the independent rollback timer."""
    with contextlib.suppress(subprocess.SubprocessError):
        command("systemctl", "--user", "stop", TIMER)


def changes(transaction):
    """Accept an in-flight single-output preview from the previous version."""
    return transaction.get("changes", [transaction])


def rollback(transaction):
    """Restore live values without modifying the saved layout."""
    if digest(config_text()) == transaction["digest"]:
        try:
            for change in changes(transaction):
                apply_rule(change["original"])
        except (ValueError, subprocess.SubprocessError):
            command("hyprctl", "reload")
    else:
        # An external editor changed the authoritative file; reload that file
        # rather than writing the older snapshot over its changes.
        command("hyprctl", "reload")
    PENDING.unlink(missing_ok=True)
    stop_timer()


def status():
    """Return real monitor values and available choices, not requested values."""
    rules = generated_rules(config_text())
    monitors = read_monitors()
    for monitor in monitors:
        monitor["editable"] = (
            monitor["name"] in rules
            and not monitor.get("disabled", False)
            and monitor.get("mirrorOf", "none") == "none"
            and monitor.get("transform", 0) <= 3
        )
        if monitor["editable"]:
            monitor["currentMode"] = mode_value(monitor)
        else:
            monitor["currentMode"] = ""
    transaction = pending()
    return {
        "monitors": monitors,
        "deadline": transaction["deadline"] if transaction else 0,
        "profiles": [{"label": profile_label(profile), "compatible": compatible(profile, monitors, rules)} for profile in read_profiles()],
    }


def verify_target(name, target):
    """Wait briefly for actual compositor readback after applying a rule."""
    for _ in range(8):
        monitor = next((entry for entry in read_monitors() if entry["name"] == name), None)
        if monitor and matches(monitor, target):
            return
        time.sleep(0.2)
    raise ValueError("Display did not confirm the requested configuration")


def identity(monitor):
    """Use compositor output name and reported hardware identity together."""
    return [monitor["name"], monitor.get("make", ""), monitor.get("model", ""), monitor.get("serial", "")]


def geometry(monitor):
    """Extract the live geometry fields owned by the preview."""
    return {"mode": mode_value(monitor), **{key: monitor[key] for key in ("scale", "transform", "x", "y")}}


def editable(monitor, rules):
    """Check whether a native generated rule can be safely edited."""
    return (
        monitor["name"] in rules
        and not monitor.get("disabled")
        and monitor.get("mirrorOf", "none") == "none"
        and monitor.get("transform", 0) <= 3
    )


def read_profiles():
    """Read the explicitly saved user layout snapshots."""
    if not PROFILES.exists():
        return []
    data = json.loads(PROFILES.read_text())
    if not isinstance(data, list) or len(data) > 12:
        raise ValueError("Invalid saved display profiles")
    return data


def write_profiles(profiles):
    """Persist user layout snapshots atomically."""
    PROFILES.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(PROFILES, json.dumps(profiles, indent=2) + "\n")


def profile_label(profile):
    """Describe each output's geometry without ambiguous labels."""
    return " · ".join(
        f"{entry['identity'][0]} {entry['target']['mode'].split('@')[0]} @ {float(entry['target']['mode'].split('@')[1]):g} Hz / {entry['target']['scale']:g}x / {entry['target']['transform'] * 90}° / ({entry['target']['x']}, {entry['target']['y']})"
        for entry in profile
    )


def compatible(profile, monitors, rules):
    """Require the same connected hardware and editable rules."""
    return (
        bool(monitors)
        and all(editable(monitor, rules) for monitor in monitors)
        and sorted(entry["identity"] for entry in profile) == sorted(identity(monitor) for monitor in monitors)
    )


def save_profile():
    """Save a distinct confirmed live layout."""
    if pending():
        raise ValueError("Keep or revert the preview first")
    monitors = read_monitors()
    rules = generated_rules(config_text())
    if not monitors or not all(editable(monitor, rules) for monitor in monitors):
        raise ValueError("Use the native display editor for this layout")
    profile = [{"identity": identity(monitor), "target": geometry(monitor)} for monitor in sorted(monitors, key=lambda item: item["name"])]
    profiles = read_profiles()
    if profile not in profiles:
        if len(profiles) >= 12:
            raise ValueError("Remove a saved layout before adding another")
        write_profiles([*profiles, profile])


def selected_profile(raw_index):
    """Resolve the selected layout within the serialized operation."""
    profiles = read_profiles()
    index = int(raw_index)
    if not 0 <= index < len(profiles):
        raise ValueError("Saved layout is unavailable")
    return profiles, index


def prepare_change(current, rule, target):
    """Validate geometry and retain all unrelated native rule fields."""
    mode, scale, transform, x, y = (target[key] for key in ("mode", "scale", "transform", "x", "y"))
    if (
        not 0.75 <= scale <= 3
        or type(transform) is not int
        or not 0 <= transform <= 3
        or type(x) is not int
        or type(y) is not int
        or abs(x) > 32768
        or abs(y) > 32768
    ):
        raise ValueError("Invalid display geometry")
    if not any(
        same_mode(mode, candidate) for candidate in [mode_value(current), *current.get("availableModes", [])] if MODE.fullmatch(candidate)
    ):
        raise ValueError("Mode is not advertised by this output")
    width, height, _ = mode_parts(mode)
    if any(abs(size / scale - round(size / scale)) > 0.001 for size in (width, height)):
        raise ValueError("Scale does not divide the advertised mode into logical pixels")
    return {
        "name": current["name"],
        "original": build_rule(rule, **geometry(current)),
        "replacement": build_rule(rule, **target),
        "target": target,
    }


def begin_preview(text, prepared, topology=None):
    """Arm rollback before applying and verifying every prepared rule."""
    if pending():
        raise ValueError("Keep or revert the existing preview first")
    transaction = {"digest": digest(text), "changes": prepared, "deadline": time.time() + 20}
    if topology is not None:
        transaction["topology"] = topology
    atomic_write(PENDING, json.dumps(transaction))
    try:
        command("systemctl", "--user", "restart", TIMER)
    except subprocess.SubprocessError:
        PENDING.unlink(missing_ok=True)
        raise
    try:
        for change in prepared:
            apply_rule(change["replacement"])
        for change in prepared:
            verify_target(change["name"], change["target"])
    except (ValueError, subprocess.SubprocessError):
        rollback(transaction)
        raise


def preview(args):
    """Validate a staged rule and arm rollback before touching the compositor."""
    name, mode, raw_scale, raw_transform, raw_x, raw_y = args
    text = config_text()
    rules = generated_rules(text)
    current = next((entry for entry in read_monitors() if entry["name"] == name), None)
    if not current or not editable(current, rules):
        raise ValueError("Use the native display editor for this layout")
    target = {"mode": mode, "scale": float(raw_scale), "transform": int(raw_transform), "x": int(raw_x), "y": int(raw_y)}
    begin_preview(text, [prepare_change(current, rules[name], target)])


def preview_profile(raw_index):
    """Preview a compatible saved layout using the native transaction."""
    profiles, index = selected_profile(raw_index)
    profile = profiles[index]
    text = config_text()
    rules = generated_rules(text)
    monitors = read_monitors()
    if not compatible(profile, monitors, rules):
        raise ValueError("Saved layout does not match the connected displays")
    by_name = {monitor["name"]: monitor for monitor in monitors}
    prepared = [prepare_change(by_name[entry["identity"][0]], rules[entry["identity"][0]], entry["target"]) for entry in profile]
    begin_preview(text, prepared, sorted(identity(monitor) for monitor in monitors))


def confirm(transaction):
    """Persist the verified preview to the existing native monitor file."""
    text = config_text()
    if time.time() >= transaction["deadline"] or digest(text) != transaction["digest"]:
        rollback(transaction)
        raise ValueError("Preview expired or the native layout changed")
    try:
        if "topology" in transaction and sorted(identity(monitor) for monitor in read_monitors()) != transaction["topology"]:
            raise ValueError("Connected displays changed during preview")
        for change in changes(transaction):
            verify_target(change["name"], change["target"])
            previous = generated_rules(text).get(change["name"])
            if not previous or text.count(previous) != 1:
                raise ValueError("Native layout changed")
            text = text.replace(previous, change["replacement"], 1)
        atomic_write(CONFIG, text, CONFIG.stat().st_mode & 0o777)
    except (ValueError, OSError, subprocess.SubprocessError):
        rollback(transaction)
        raise
    PENDING.unlink(missing_ok=True)
    stop_timer()


def main(args):
    """Serialize preview, rollback and confirmation, including timer callbacks."""
    with (RUNTIME / "desktop-shell-display-preview.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        action = args[0] if args else "status"
        transaction = pending()
        if transaction and (action == "rollback" or time.time() >= transaction["deadline"]):
            rollback(transaction)
            transaction = None
        if action == "preview":
            preview(args[1:])
        elif action == "save-profile":
            save_profile()
        elif action == "preview-profile":
            preview_profile(args[1])
        elif action == "delete-profile":
            if transaction:
                raise ValueError("Keep or revert the preview first")
            profiles, index = selected_profile(args[1])
            write_profiles(profiles[:index] + profiles[index + 1 :])
        elif action == "keep":
            if not transaction:
                raise ValueError("No active preview")
            confirm(transaction)
        elif action not in ("status", "rollback"):
            raise ValueError("Unknown display action")
        print(json.dumps(status()))


if __name__ == "__main__":
    try:
        main(sys.argv[1:])
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
